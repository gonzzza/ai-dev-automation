// Bundles the action into dist/index.js and writes dist/THIRD_PARTY_LICENSES.txt next to it.
// dist/ is committed and redistributes the bundled packages, and their licenses (mostly MIT)
// require their notices to travel with them. esbuild's legal-comments option only keeps license
// comments found in the source, which most packages don't have, so this copies each bundled
// package's LICENSE file instead. Run with `npm run build -w review-action`.
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const NODE_MODULES = "node_modules/";
const LICENSE_FILE = /^(licen[cs]e|copying|notice)/i;

/**
 * The package directories that bundled files came from, given esbuild's metafile input paths.
 * Files outside node_modules are this repo's own code, covered by its LICENSE.
 */
export function bundledPackageDirs(inputs: readonly string[]): string[] {
  const dirs = new Set<string>();
  for (const input of inputs) {
    const path = input.replaceAll("\\", "/");
    const at = path.lastIndexOf(NODE_MODULES); // the innermost package, for nested node_modules
    if (at === -1) continue;
    const root = path.slice(0, at + NODE_MODULES.length);
    const segments = path.slice(root.length).split("/");
    const nameLength = segments[0]?.startsWith("@") ? 2 : 1;
    dirs.add(root + segments.slice(0, nameLength).join("/"));
  }
  return [...dirs];
}

export interface PackageFiles {
  readFile(path: string): string;
  readdir(path: string): string[];
}

interface PackageJson {
  name?: string;
  version?: string;
  license?: string;
  repository?: string | { url?: string };
}

/**
 * The notices file: each package's name, version, license and license files, sorted by name.
 * A package without a license file (some publish only the package.json field) gets its license
 * and repository instead. Throws if a package states no license at all, so a dependency with
 * unknown terms can't be bundled unnoticed.
 */
export function renderNotices(dirs: readonly string[], files: PackageFiles): string {
  const sections = new Map<string, string>();
  for (const dir of dirs) {
    const pkg = JSON.parse(files.readFile(`${dir}/package.json`)) as PackageJson;
    const id = `${pkg.name ?? dir}@${pkg.version ?? "unknown"}`;
    const licenseFiles = files.readdir(dir).filter((name) => LICENSE_FILE.test(name)).sort();
    if (licenseFiles.length === 0 && !pkg.license) {
      throw new Error(`${id} states no license: check its terms before bundling it`);
    }
    const texts = licenseFiles.map((name) => files.readFile(`${dir}/${name}`).replaceAll("\r\n", "\n").trim());
    if (texts.length === 0) {
      const repository = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
      texts.push(`The package ships no license file.${repository ? ` Source: ${repository}` : ""}`);
    }
    sections.set(id, [`${id} (${pkg.license ?? "license not stated"})`, ...texts].join("\n\n"));
  }
  const body = [...sections.keys()].sort().map((id) => sections.get(id));
  const header = "Third-party software bundled in dist/index.js. Generated by scripts/build.ts: do not edit.";
  return [header, ...body].join(`\n\n${"-".repeat(72)}\n\n`) + "\n";
}

async function main(): Promise<void> {
  const result = await build({
    entryPoints: ["src/main.ts"],
    bundle: true,
    platform: "node",
    target: "node24",
    format: "esm",
    outfile: "dist/index.js",
    legalComments: "none", // the notices go in THIRD_PARTY_LICENSES.txt instead
    // Some bundled CommonJS packages call require(), which an ESM bundle doesn't have.
    banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
    metafile: true,
    logLevel: "info",
  });
  const dirs = bundledPackageDirs(Object.keys(result.metafile.inputs));
  const notices = renderNotices(dirs, {
    readFile: (path) => readFileSync(path, "utf8"),
    readdir: (path) => readdirSync(path),
  });
  writeFileSync("dist/THIRD_PARTY_LICENSES.txt", notices);
  console.log(`dist/THIRD_PARTY_LICENSES.txt: ${dirs.length} packages`);
}

if (import.meta.main) {
  await main();
}
